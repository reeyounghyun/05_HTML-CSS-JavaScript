// 매개변수 : 함수를 정의할 때 쓰는 이름
// 인자 : 함수를 호출할 때 실제로 넘기는 값

// 자바와 다른 점
// 자바스크립트는 매개변수와 인자의 개수가 일치하지 않아도 동작한다.
// 왜? 함수를 호출할 때 인자 개수를 검사하지 않기 때문 (Java는 컴파일러가 실행 전에 개수와 타입을 확인함)

// 매개변수 위치에 기본값을 설정할 수 있다.
function hello(name = "아무개") {
  return `${name}님 안녕하세요!`;
}

console.log(hello("bear")); // 정상
console.log(hello("bear", "cat")); // 초과된 인수는 무시됨
console.log(hello()); // 인자가 없으면 기본값 사용
